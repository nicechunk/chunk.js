import { constants } from "node:fs";
import { access, copyFile, mkdtemp, readFile, rename, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const checkOnly = process.argv[2] === "--check";
if ((process.argv.length > 2 && !checkOnly) || process.argv.length > 3) {
  throw new Error("Usage: node tools/build-browser-runtime.mjs [--check]");
}

const outputs = Object.freeze([
  Object.freeze({ source: "src/browser-runtime.js", output: "chunk/browser-runtime.js" }),
  Object.freeze({ source: "chunk/chunk-build-worker.js", output: "chunk/chunk-build-worker.bundle.js" }),
]);
const temporaryDirectory = await mkdtemp(join(tmpdir(), "chunk-js-browser-runtime-"));

try {
  for (const entry of outputs) {
    const temporaryOutput = join(temporaryDirectory, basename(entry.output));
    const result = await build({
      absWorkingDir: root,
      entryPoints: [entry.source],
      outfile: temporaryOutput,
      bundle: true,
      format: "esm",
      platform: "browser",
      target: ["es2022"],
      minify: true,
      legalComments: "none",
      sourcemap: false,
      metafile: true,
      banner: { js: "// Generated by npm run build:browser. Do not edit directly." },
      logLevel: "silent",
    });
    const outputMetadata = Object.values(result.metafile.outputs);
    if (outputMetadata.length !== 1 || outputMetadata[0].imports.length !== 0) {
      throw new Error(`${entry.output} is not a self-contained browser module.`);
    }

    const destination = join(root, entry.output);
    if (checkOnly) {
      await access(destination, constants.R_OK);
      const [expected, actual] = await Promise.all([readFile(temporaryOutput), readFile(destination)]);
      if (!expected.equals(actual)) throw new Error(`${entry.output} is stale; run npm run build:browser.`);
      continue;
    }

    const staged = `${destination}.tmp-${process.pid}`;
    await copyFile(temporaryOutput, staged);
    await rename(staged, destination);
  }
  console.log(checkOnly ? "Browser runtime bundles are current." : "Browser runtime bundles generated.");
} finally {
  await rm(temporaryDirectory, { recursive: true, force: true });
}
